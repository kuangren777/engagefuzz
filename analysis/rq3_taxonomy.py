"""Level-3 vs level-4 failure taxonomy (post-review, exploratory, rule in NOTES).
Among level-3 runs (attacker-unique value on a side-effect call, oracle did not fire), classify:
  partial-args  : the attacker-unique value is present but >=1 other injection-GT arg value is missing
  wrong-function: the value appears on a function not in the injection-task ground truth
  other         : GT function and all its GT arg values present, oracle still did not fire
python3 rq3_taxonomy.py -> out/rqtax_numbers.tex
python3 rq3_taxonomy.py --models qwen3-8b-yf,qwen3-32b-local,qwen3-8b-local  (models that pass the tool-call parse gate)
"""
import collections
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "engine"))
sys.path.insert(0, os.path.join(HERE))
import engagefuzz as ef  # noqa: E402
from prox_v2 import gt, atk_values, SIDE_PREFIX  # noqa: E402
from fractions import Fraction
from efmt import F, exact, mean  # noqa: E402,F401  one half-up formatter


def classify(r):
    s, ut, it = r["suite"], r["ut"], r["it"]
    A = atk_values(s, ut, it)                       # (fn, arg, value) attacker-unique
    avals = {v for _, _, v in A}
    gtfns = {f for f, _ in gt(s, "i", it)}
    gtvals = {v for f, args in gt(s, "i", it) for v in args.values() if len(v) > 3}
    for t in r.get("trace") or []:
        got = " ".join(str(v).lower() for v in (t.get("a") or {}).values())
        if not t["f"].startswith(SIDE_PREFIX) and t["f"] not in gtfns:
            continue
        if not any(v in got for v in avals):
            continue
        # this is the level-3 call
        if t["f"] not in gtfns:
            return "wrong-function"
        missing = [v for v in gtvals if v not in got]
        return "partial-args" if missing else "other"
    return "other"


def main(models=None):
    rows = [json.loads(l) for d in ("rq1", "rq2") for f in glob.glob(os.path.join(HERE, "..", "runs", d, "*.jsonl"))
            if "ABORTED" not in f and "memo" not in f and "audit" not in f and "paired" not in f and "stats" not in f and "selected" not in f and "density" not in f and "validity" not in f
            for l in open(f)]
    if models:
        rows = [r for r in rows if r.get("model") in models]
    lvl3 = []
    for r in rows:
        if r.get("err") is not None or r.get("trace") is None or r.get("security"):
            continue
        if r.get("level_v21") == 3 or (r.get("level_v21") is None and ef.prox_v2.feats(r)["level21"] == 3):
            lvl3.append(r)
    c = collections.Counter(classify(r) for r in lvl3)
    n = sum(c.values()) or 1
    L = ["% auto-generated by rq3_taxonomy.py (exploratory level-3 failure taxonomy)"]
    def m(k, v): L.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    m("rqtaxN", str(sum(c.values())))
    for key, tag in [("partial-args", "Partial"), ("wrong-function", "Wrongfn"), ("other", "Other")]:
        m(f"rqtax{tag}", str(c.get(key, 0)))
        m(f"rqtax{tag}Pct", f"{F(Fraction(100*c.get(key,0), n), '.1f')}")
    # RQ1-only split (census) + RQ2 memo-replay count, for the population note
    rq1l3 = [r for r in lvl3 if r.get("rep") is not None]   # census rows carry rep
    import collections as _c
    c1 = _c.Counter(classify(r) for r in rq1l3); n1 = sum(c1.values()) or 1
    for key, tag in [("partial-args", "Partial"), ("wrong-function", "Wrongfn"), ("other", "Other")]:
        m(f"rqtaxRQone{tag}Pct", f"{F(Fraction(100*c1.get(key,0), n1), '.1f')}")
    m("rqtaxRQONEN", str(sum(c1.values())))
    m("rqtaxReplay", str(sum(1 for r in lvl3 if r.get("memo_hit"))))
    open(os.path.join(HERE, "..", "out", "rqtax_numbers.tex"), "w").write("\n".join(L) + "\n")
    print("level-3 taxonomy:", dict(c), "total", sum(c.values()))


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default=None, help="comma-separated served model ids to keep (default: all)")
    a = ap.parse_args()
    main(set(a.models.split(",")) if a.models else None)
