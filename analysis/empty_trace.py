"""Runs without a tool call (empty trace), post-hoc. Offline, zero model calls.
python3 empty_trace.py -> runs/px/empty_trace.json + out/emptytrace_table.tex (SI)
                          + out/empty_numbers.tex (SI sensitivity macros)

An empty run is error-free with trace == []. It is never exposed, so prox_v2 gives it level 0, and no
empty run violates. Rates: RQ1 census rows per model; RQ2 fresh executions (memo hits excluded) per reward
variant on Qwen3-8B. Sensitivity: the pooled model-centred same-repetition rho (rq1_stats.py), the pooled
held-out rho (rq1_heldout.py) and the number of models passing the pre-registered per-model test (one-sided
Spearman, Holm over four), each recomputed without empty runs. Same unit key, level and rate definitions.
"""
import collections
import glob
import json
import os
import re
import sys
from fractions import Fraction

from scipy.stats import spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rq1_samepop as S  # noqa: E402  cells(), same_rep(), held_out(), centre()
from efmt import F  # noqa: E402  one half-up formatter

OUT = os.path.join(HERE, "..", "runs", "px", "empty_trace.json")
TAB = os.path.join(HERE, "..", "out", "emptytrace_table.tex")
NUM = os.path.join(HERE, "..", "out", "empty_numbers.tex")
R2 = os.path.join(HERE, "..", "runs", "rq2")
PAT = re.compile(r"(.+?)_(None|both)_(banking|slack|travel)_(user_task_\d+)_(injection_task_\d+)_([a-z0-9-]+)_(\d+)\.jsonl$")
VARIANTS = [("random", "random"), ("binary", "binary success"), ("coverage", "coverage"),
            ("prox-v21", "proximity"), ("tmap-ladder", "T-MAP ladder")]


def holm_pass(ps_rhos):
    ps = [1.0 if p is None else p for p, _ in ps_rhos]
    order = sorted(range(len(ps)), key=lambda i: ps[i])
    adj, run = [0.0] * len(ps), 0.0
    for k, i in enumerate(order):
        run = max(run, min(1.0, (len(ps) - k) * ps[i]))
        adj[i] = run
    return sum(1 for a, (_, r) in zip(adj, ps_rhos) if a < 0.05 and r is not None and r > 0)


def rq1(drop_empty):
    pool_sr, pool_ho, tests = [], [], []
    for mk in S.MODELS:
        c = S.cells(mk)
        if drop_empty:
            c = {u: [r for r in v if r["trace"] != []] for u, v in c.items()}
        sr = [p for p in (S.same_rep(v) for v in c.values() if v) if p]
        ho = [p for p in (S.held_out(v) for v in c.values() if v) if p]
        t = S.rho(sr, "greater")
        tests.append((t["p"], t["rho"]))
        pool_sr += S.centre(sr)
        pool_ho += S.centre(ho)
    a = spearmanr([p[0] for p in pool_sr], [p[1] for p in pool_sr])
    b = spearmanr([p[0] for p in pool_ho], [p[1] for p in pool_ho])
    return dict(pooled_same=float(a[0]), pooled_same_n=len(pool_sr), pooled_heldout=float(b[0]),
                pooled_heldout_n=len(pool_ho), pass_models=holm_pass(tests))


def main():
    rates = {}
    for mk in S.MODELS:
        rows = [r for v in S.cells(mk).values() for r in v]
        rates["rq1|" + mk] = dict(n=len(rows), empty=sum(r["trace"] == [] for r in rows),
                                  empty_viol=sum(r["trace"] == [] and bool(r["security"]) for r in rows))
    c = collections.defaultdict(lambda: dict(n=0, empty=0, empty_viol=0))
    for f in glob.glob(os.path.join(R2, "*_[0-9].jsonl")):
        m = PAT.match(os.path.basename(f))
        if not m or m.group(1) != "qwen3-8b-local":
            continue
        for line in open(f):
            r = json.loads(line)
            if r.get("err") is not None or r.get("memo_hit"):
                continue
            d = c["rq2|" + m.group(6)]
            d["n"] += 1
            d["empty"] += r.get("trace") == []
            d["empty_viol"] += r.get("trace") == [] and bool(r["security"])
    rates.update(c)
    assert all(v["empty_viol"] == 0 for v in rates.values())
    full, drop = rq1(False), rq1(True)
    res = dict(rates=rates, with_empty=full, without_empty=drop)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(res, open(OUT, "w"), indent=1)

    pct = lambda d: F(Fraction(100 * d["empty"], d["n"]), ".1f")
    rows = [("RQ1", S.NAMES[mk], rates["rq1|" + mk]) for mk in S.MODELS]
    rows += [("RQ2 Qwen3-8B", name, rates["rq2|" + v]) for v, name in VARIANTS]
    T = ["% auto-generated by empty_trace.py; do not hand-edit",
         r"\begin{table}[t]\centering",
         r"\caption{Runs in which the agent calls no tool. For RQ1 the count is over the census runs of each model. "
         r"For RQ2 it is over the fresh executions of each reward \varword{} on Qwen3-8B, where executions served from the memo are left out. "
         r"Such a run has level zero and none of them is a violation.}",
         r"\label{tab:emptytrace}",
         r"\begin{tabular}{llrrr}", r"\toprule",
         r"Question & Model or \varword{} & Runs & No tool call & Share \% \\", r"\midrule"]
    last = None
    for q, name, d in rows:
        if last is not None and q != last:
            T.append(r"\midrule")
        T.append(f"{q if q != last else ''} & {name} & {d['n']} & {d['empty']} & {pct(d)} \\\\")
        last = q
    T += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    open(TAB, "w").write("\n".join(T) + "\n")

    L = ["% auto-generated by empty_trace.py"]
    m = lambda k, v: L.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    m("emptyPooledSame", F(full["pooled_same"], ".3f")); m("emptyPooledSameDrop", F(drop["pooled_same"], ".3f"))
    m("emptyPooledHo", F(full["pooled_heldout"], ".3f")); m("emptyPooledHoDrop", F(drop["pooled_heldout"], ".3f"))
    m("emptyPass", str(full["pass_models"])); m("emptyPassDrop", str(drop["pass_models"]))
    open(NUM, "w").write("\n".join(L) + "\n")
    print(json.dumps(dict(with_empty=full, without_empty=drop), indent=1))
    for q, name, d in rows:
        print(q, name, d["n"], d["empty"], pct(d))


if __name__ == "__main__":
    main()
