"""Parse-gate disclosure macros for the SI.
Unparsed share = error-free runs whose final answer still holds a tool-call JSON object
(s1b_reparse.calls_in_text), over error-free runs. Tool-call rate = error-free runs with at least one executed call.
Stages for Llama-3.1-8B: RQ1 census (runs/rq1), the parser smoke with llama3_json (runs/rq1_parsed), RQ2 campaigns.
python3 parse_gate_numbers.py -> out/gate_numbers.tex
"""
import glob
import json
import os
from fractions import Fraction

from efmt import F
from s1b_reparse import calls_in_text

H = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(H, "..", "runs")
STAGES = [("Census", [os.path.join(R, "rq1", "census_llama31-8b-local.jsonl")]),
          ("Smoke", [os.path.join(R, "rq1_parsed", "census_llama31-8b-local.jsonl")]),
          ("Campaign", glob.glob(os.path.join(R, "rq2", "llama31-8b-local_*_[0-9].jsonl")))]
L = ["% auto-generated by parse_gate_numbers.py (Llama-3.1-8B parse gate)"]
def m(k, v): L.append(f"\\newcommand{{\\{k}}}{{{v}}}")
for tag, files in STAGES:
    rows = [json.loads(l) for f in files for l in open(f)]
    ok = [r for r in rows if r.get("err") is None]
    unparsed = sum(1 for r in ok if calls_in_text(r.get("final") or ""))
    called = sum(1 for r in ok if r.get("trace"))
    m(f"gateLlama{tag}N", f"{len(ok):,}")
    m(f"gateLlama{tag}Unparsed", F(Fraction(100 * unparsed, len(ok)), ".1f"))
    m(f"gateLlama{tag}Called", F(Fraction(100 * called, len(ok)), ".1f"))
    print(tag, len(ok), unparsed, called)
open(os.path.join(H, "..", "out", "gate_numbers.tex"), "w").write("\n".join(L) + "\n")
