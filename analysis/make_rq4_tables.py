"""RQ4 LaTeX table generators, ready for when the data lands (both are shelved until then).
  (a) definition ablation: reward arms prox-v1 / prox-v2 / prox-v21 / judge-ladder, from the paired
      analysis json (rq2_paired.py --json) of the E4a run on one backend.
  (b) InjecAgent transfer: fail-only rho of the ladder vs trigger rate, from an rq1-style json.

python3 make_rq4_tables.py <e4a_paired.json|-> <injecagent_rq1.json|-> > out/rq4_tables.tex
Pass - for a file that does not exist yet; the generator emits a visible TODO row instead.
"""
import json
import os
import sys

ARMS = [("prox-v21", "v2.1 attacker-unique value (ours)"), ("prox-v2", "v2 any side-effect"),
        ("prox-v1", "v1 target function name"), ("judge-ladder", "LLM-judge 0--4")]


def ablation(path):
    out = [r"\begin{table}[t]\centering",
           r"\caption{RQ4 definition ablation. Each reward arm drives the same scheduler at an equal "
           r"budget on one backend. We report violations per campaign and the paired effect size "
           r"$\hat A_{12}$ of \texttt{prox-v21} against the arm ($\uparrow$ better for \texttt{prox-v21}).}",
           r"\label{tab:rq4ablation}", r"\begin{tabular}{lcc}", r"\toprule",
           r"Reward & viol/campaign & $\hat A_{12}$ vs v2.1 \\", r"\midrule"]
    if path == "-" or not os.path.exists(path):
        out.append(r"\multicolumn{3}{c}{\emph{[E4a run pending; filled on completion]}} \\")
    else:
        d = json.load(open(path))
        for key, name in ARMS:
            vm = d["arms"].get(key, {}).get("viol_mean")
            a12 = d["tests"].get("primary_viol", {}).get(key, {}).get("A12") if key != "prox-v21" else None
            tag = "(ours)" if key == "prox-v21" else ""
            vmc = "--" if vm is None else f"{vm:.2f}"
            a12c = "--" if a12 is None else f"{a12:.3f}"
            row = f"{name} & {vmc} & {a12c} \\\\"
            out.append(r"\textbf{" + row + "}" if key == "prox-v21" else row)
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(out)


def transfer(path):
    out = [r"\begin{table}[t]\centering",
           r"\caption{RQ4 transfer to InjecAgent. Fail-only rank correlation $\rho$ of the proximity "
           r"ladder with the trigger rate, on two open models ($\uparrow$ better).}",
           r"\label{tab:rq4transfer}", r"\begin{tabular}{lcc}", r"\toprule",
           r"Model & $\rho$ $\uparrow$ & $p$ \\", r"\midrule"]
    if path == "-" or not os.path.exists(path):
        out.append(r"\multicolumn{3}{c}{\emph{[InjecAgent census pending; filled on completion]}} \\")
    else:
        d = json.load(open(path))
        for m, r in d.items():
            if isinstance(r, dict) and "rho" in r.get("rho", {}).get("v21_minfail1", {"rho": None}):
                p = r["rho"]["v21_minfail1"]
                out.append(f"{m} & {p['rho']:.3f} & {p['p']:.3g} \\\\")
    out += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(out)


if __name__ == "__main__":
    e4a = sys.argv[1] if len(sys.argv) > 1 else "-"
    inj = sys.argv[2] if len(sys.argv) > 2 else "-"
    print("% auto-generated by make_rq4_tables.py (E4a ablation cancelled)\n" + transfer(inj))
