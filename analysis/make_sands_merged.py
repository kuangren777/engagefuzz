"""Merged floats for the S&S main text (12-float limit), built only from already generated
tables and committed run data. No number is typed here.
python3 make_sands_merged.py -> out/{frontier_merged_table,rq2_detail_table}.tex,
                                out/figs/{frontier_levels,rq4_spread}.pdf
"""
import json
import os
import re
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.join(HERE, "..", "out")
FIGS = os.path.join(PAPER, "figs")
sys.path.insert(0, HERE)
import make_figs2 as f2  # noqa: E402

plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False})
COLORS = ["#d9d9d9", "#bdbdbd", "#fdae6b", "#e6550d", "#a50f15"]


def read(name):
    return open(os.path.join(PAPER, name)).read()


def part(src, start, end):
    """Text between the first `start` and the following `end`, exclusive."""
    i = src.index(start) + len(start)
    return src[i:src.index(end, i)]


def caption(src):
    s = src[src.index(r"\caption{") + len(r"\caption{"):]
    depth, out = 1, []
    for ch in s:
        depth += (ch == "{") - (ch == "}")
        if depth == 0:
            break
        out.append(ch)
    return "".join(out)


def body_rows(src):
    rows = part(src, r"\midrule", r"\bottomrule").strip().split("\n")
    return [r.strip() for r in rows if r.strip()]


def cells(row):
    return [c.strip() for c in re.sub(r"\\\\\s*$", "", row).split("&")]


def frontier_table():
    ad, ia = read("rq3_permodel_table.tex"), read("rq4_frontier_table.tex")
    ia_rows = {cells(r)[0]: cells(r) for r in body_rows(ia)}
    runs = sorted({v[1] for v in ia_rows.values()})
    assert len(runs) == 1, runs
    out = []
    for r in body_rows(ad):
        c = cells(r)
        i = ia_rows[c[0]]
        out.append(" & ".join(c + [i[2], i[3]]) + r" \\")
    cap = (caption(ad).replace("AgentDojo frontier density per model. Runs,", "Frontier density per model in AgentDojo and InjecAgent. The AgentDojo columns give the runs,") + " The last two columns give the InjecAgent attack-success rate and the share of "
           "binary-failure runs at level two or higher under the pre-registered InjecAgent ladder, over "
           f"{runs[0]} runs per model.")
    tex = [r"\begin{table}[t]\centering\small", r"\caption{" + cap + "}", r"\label{tab:rq3pm}",
           r"\setlength{\tabcolsep}{4pt}",
           r"\begin{tabular}{lccccccc|cc}", r"\toprule",
           r" & \multicolumn{7}{c|}{AgentDojo} & \multicolumn{2}{c}{InjecAgent} \\",
           r"Model & runs & ASR & failures & L3 runs & L3 share $\uparrow$ & floor $\downarrow$ & $p$ $\downarrow$ "
           r"& ASR & $\geq$L2 $\uparrow$ \\", r"\midrule"] + out + [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    open(os.path.join(PAPER, "frontier_merged_table.tex"), "w").write(
        "% auto-generated by make_sands_merged.py from rq3_permodel_table.tex and rq4_frontier_table.tex\n"
        + "\n".join(tex) + "\n")


def rq2_detail_table():
    su, tg = read("rq2_suite_table.tex"), read("rq2_targets_table.tex")
    cap = (caption(su).rstrip(".") + ". " + caption(tg)).replace(
        "Llama-3.1-8B fails the tool-call parse gate. Per-target", "Per-target")
    cap = "Upper part, " + cap[0].lower() + cap[1:]
    cap = cap.replace(" Per-target view of RQ4, post-hoc.", " Lower part, per-target view of RQ4, post-hoc.")

    def tab(src):
        return src[src.index(r"\begin{tabular}"):src.index(r"\end{tabular}") + len(r"\end{tabular}")]
    tex = [r"\begin{table}[t]\centering", r"\caption{" + cap + "}", r"\label{tab:rq2suite}",
           tab(su), r"\par\medskip", tab(tg), r"\end{table}"]
    open(os.path.join(PAPER, "rq2_detail_table.tex"), "w").write(
        "% auto-generated by make_sands_merged.py from rq2_suite_table.tex and rq2_targets_table.tex\n"
        + "\n".join(tex) + "\n")


def frontier_levels():
    import glob
    sys.path.insert(0, os.path.join(HERE, "..", "engine"))
    import engagefuzz as ef
    R = [json.loads(l) for l in open(os.path.join(HERE, "..", "testbed", "data", "frontier.jsonl"))]
    R = [r for r in R if r.get("err") is None and r.get("trace") is not None]
    nv = [r for r in R if not r["security"]]
    lv = [ef.prox_v2.feats(r)["level21"] for r in nv]
    asr = 100 * sum(bool(r["security"]) for r in R) / max(1, len(R))
    fig, (a, b) = plt.subplots(1, 2, figsize=(6.6, 3.0), gridspec_kw={"width_ratios": [1, 3]})
    bottom = 0.0
    for lvl in range(4):
        fr = sum(x == lvl for x in lv) / max(1, len(lv))
        a.bar([0], [fr], bottom=bottom, color=COLORS[lvl], width=0.6)
        bottom += fr
    a.set_xticks([0]); a.set_xticklabels([f"pooled\nASR {asr:.1f}%"])
    a.set_xlim(-0.6, 0.6); a.set_ylabel("share of runs")
    a.set_title("(a) AgentDojo failures", fontsize=9)
    files = sorted(glob.glob(os.path.join(f2.RUNS, "rq4", "injecagent_frontier_*.jsonl")))
    models = [os.path.basename(f).split("injecagent_frontier_")[1].replace(".jsonl", "") for f in files]
    data = [[json.loads(l) for l in open(f) if json.loads(l)["err"] is None] for f in files]
    bottoms = [0.0] * len(files)
    for lvl in range(1, 5):
        fr = [sum(r["level_ia"] == lvl for r in R) / max(1, len(R)) for R in data]
        b.bar(models, fr, bottom=bottoms, color=COLORS[lvl])
        bottoms = [x + y for x, y in zip(bottoms, fr)]
    b.tick_params(axis="x", rotation=25)
    b.set_title("(b) InjecAgent, all runs per model", fontsize=9)
    handles = [plt.Rectangle((0, 0), 1, 1, color=COLORS[l]) for l in range(5)]
    fig.legend(handles, [f"level {l}" for l in range(5)], ncol=5, frameon=False, loc="upper center",
               bbox_to_anchor=(0.5, 1.0))
    fig.tight_layout(rect=(0, 0, 1, 0.92)); fig.savefig(os.path.join(FIGS, "frontier_levels.pdf"))


def rq4_spread():
    fig, (a, b) = plt.subplots(1, 2, figsize=(6.6, 2.9))
    by = f2.load_campaigns("qwen3-8b-local")
    a.boxplot([[v for v, _ in by[x]] for x in f2.ARMS], showmeans=True, widths=0.6,
              tick_labels=[f2.ARMLBL[x] for x in f2.ARMS])
    a.set_ylabel("violations per campaign"); a.tick_params(axis="x", rotation=20)
    a.set_title("(a) Qwen3-8B, per campaign", fontsize=9)
    x = range(len(f2.ARMS)); w = 0.35
    for mi, (mk, disp) in enumerate([("qwen3-8b-local", "Qwen3-8B"), ("llama31-8b-local", "Llama-3.1-8B")]):
        d = f2.load_campaigns(mk)
        allm = [sum(v for v, _ in d[k]) / max(1, len(d[k])) for k in f2.ARMS]
        frm = [sum(fv for _, fv in d[k]) / max(1, len(d[k])) for k in f2.ARMS]
        off = -w / 2 if mi == 0 else w / 2
        b.bar([i + off for i in x], allm, w, label=f"{disp} all", alpha=0.9)
        b.bar([i + off for i in x], frm, w, label=f"{disp} fresh", alpha=0.5, hatch="//")
    b.set_xticks(list(x)); b.set_xticklabels([f2.ARMLBL[k] for k in f2.ARMS], rotation=20)
    b.set_ylabel("mean violations per campaign"); b.legend(fontsize=7, frameon=False)
    b.set_title("(b) all and fresh executions", fontsize=9)
    fig.tight_layout(); fig.savefig(os.path.join(FIGS, "rq4_spread.pdf"))


if __name__ == "__main__":
    frontier_table(); rq2_detail_table(); frontier_levels(); rq4_spread()
    print("wrote frontier_merged_table.tex, rq2_detail_table.tex, figs/frontier_levels.pdf, figs/rq4_spread.pdf")
