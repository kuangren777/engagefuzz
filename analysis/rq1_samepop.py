"""Same-population comparison for Table 3. Offline, zero model calls.
python3 rq1_samepop.py -> runs/px/rq1_samepop.json + out/rq1samepop_table.tex (SI)

Table 3 sets the same-repetition rho (units with a failed run among all repetitions) against the
held-out rho (units with a failed run among the even repetitions). The populations differ. Here the
same-repetition rho is recomputed on exactly the held-out units, per model and pooled after centring
each model, so the drop from same-repetition to held-out can be read on one population. Same unit
key, level (v2.1) and trigger-rate definitions as rq1_stats.py and rq1_heldout.py. Report only.
"""
import collections
import glob
import json
import os
import statistics as st
import sys

from scipy.stats import spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "engine"))
import engagefuzz as ef  # noqa: E402
from efmt import F  # noqa: E402  one half-up formatter

MODELS = ["qwen3-8b-yf", "qwen3-32b-local", "llama31-8b-local", "granite31-8b-local"]
OUT = os.path.join(HERE, "..", "runs", "px", "rq1_samepop.json")
TAB = os.path.join(HERE, "..", "out", "rq1samepop_table.tex")
NAMES = {"qwen3-8b-yf": "Qwen3-8B", "qwen3-32b-local": "Qwen3-32B",
         "llama31-8b-local": "Llama-3.1-8B", "granite31-8b-local": "Granite-3.1-8B"}


def cells(mk):
    files = [f for f in glob.glob(os.path.join(HERE, "..", "runs", "rq1", f"census_{mk}*.jsonl")) if "ABORTED" not in f]
    R = [json.loads(l) for f in files for l in open(f)]
    R = [r for r in R if r.get("err") is None and r.get("trace") is not None]
    c = collections.defaultdict(list)
    for r in R:
        r["_lv"] = ef.prox_v2.feats(r)["level21"]
        c[(r["suite"], r["ut"], r["it"], r["defense"])].append(r)
    return c


def same_rep(v):
    fail = [x for x in v if not x["security"]]
    return (st.mean(x["_lv"] for x in fail), st.mean(bool(x["security"]) for x in v)) if fail else None


def held_out(v):
    A = [x for x in v if x["rep"] % 2 == 0]
    B = [x for x in v if x["rep"] % 2 == 1]
    fa = [x for x in A if not x["security"]]
    return (st.mean(x["_lv"] for x in fa), st.mean(bool(x["security"]) for x in B)) if A and B and fa else None


def rho(pairs, alt):
    X, Y = [p[0] for p in pairs], [p[1] for p in pairs]
    if len(X) < 3 or len(set(X)) < 2 or len(set(Y)) < 2:
        return dict(n=len(X), rho=None, p=None)
    r = spearmanr(X, Y, alternative=alt)
    return dict(n=len(X), rho=float(r[0]), p=float(r[1]))


def centre(pairs):
    if not pairs:
        return []
    mx, my = st.mean(p[0] for p in pairs), st.mean(p[1] for p in pairs)
    return [(a - mx, b - my) for a, b in pairs]


def main():
    res, pool = {}, collections.defaultdict(list)
    for mk in MODELS:
        c = cells(mk)
        sr_all = {u: same_rep(v) for u, v in c.items() if same_rep(v)}
        ho = {u: held_out(v) for u, v in c.items() if held_out(v)}
        assert set(ho) <= set(sr_all)        # an even-half failure is a failure among all repetitions
        sr_sub = [sr_all[u] for u in ho]
        res[mk] = dict(same_rep_full=rho(list(sr_all.values()), "greater"),
                       same_rep_on_heldout_units=rho(sr_sub, "greater"),
                       same_rep_on_heldout_units_two_sided=rho(sr_sub, "two-sided"),
                       held_out=rho(list(ho.values()), "two-sided"),
                       dropped_units=len(sr_all) - len(ho))
        pool["same_rep_full"] += centre(list(sr_all.values()))
        pool["same_rep_on_heldout_units"] += centre(sr_sub)
        pool["held_out"] += centre(list(ho.values()))
    res["pooled_centred"] = {k: rho(v, "two-sided") for k, v in pool.items()}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(res, open(OUT, "w"), indent=1)
    write_table(res)
    f = lambda d: f"n={d['n']} rho={F(d['rho'], '.3f') if d['rho'] is not None else 'nan'} p={F(d['p'], '.3g') if d['p'] is not None else 'nan'}"
    for k, d in res.items():
        print(k, {x: (f(y) if isinstance(y, dict) else y) for x, y in d.items()})


def write_table(res):
    r = lambda d: F(d["rho"], ".3f")
    rows = [(NAMES[mk], res[mk]["same_rep_full"], res[mk]["same_rep_on_heldout_units"], res[mk]["held_out"])
            for mk in MODELS]
    pc = res["pooled_centred"]
    T = ["% auto-generated by rq1_samepop.py; do not hand-edit",
         "\\begin{table}[t]\\centering",
         "\\caption{RQ1 held-out control on one population. The first two columns give the same-repetition rank "
         "correlation over all units with a failed run. The last three columns restrict to the held-out units, which "
         "are the units with a failed run among the even repetitions. On these units they give the same-repetition "
         "and the held-out rank correlation. Each $n$ counts units. The pooled row centres each model before pooling.}",
         "\\label{tab:rq1samepop}",
         "\\begin{tabular}{lccccc}",
         "\\toprule",
         " & \\multicolumn{2}{c}{all units with a failed run} & \\multicolumn{3}{c}{held-out units} \\\\",
         "Model & $n$ & same-repetition $\\rho$ $\\uparrow$ & $n$ & same-repetition $\\rho$ $\\uparrow$ & held-out $\\rho$ $\\uparrow$ \\\\",
         "\\midrule"]
    for name, a, b, c in rows:
        assert b["n"] == c["n"]
        T.append(f"{name} & {a['n']} & {r(a)} & {b['n']} & {r(b)} & {r(c)} \\\\")
    T += ["\\midrule",
          f"Pooled & {pc['same_rep_full']['n']} & {r(pc['same_rep_full'])} & {pc['held_out']['n']} & "
          f"{r(pc['same_rep_on_heldout_units'])} & {r(pc['held_out'])} \\\\",
          "\\bottomrule", "\\end{tabular}", "\\end{table}"]
    open(TAB, "w").write("\n".join(T) + "\n")


if __name__ == "__main__":
    main()
