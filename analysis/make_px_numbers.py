"""Macros for the plan §10 construct-validity checks, from runs/px/*.json (no hand values).
python3 make_px_numbers.py -> out/px_numbers.tex"""
import json, os
H = os.path.dirname(os.path.abspath(__file__)); PX = os.path.join(H, "..", "runs", "px")
s = json.load(open(os.path.join(PX, "px2_summary.json"))); c = json.load(open(os.path.join(PX, "px1a.json")))
L = ["% auto-generated by make_px_numbers.py (plan §10)"]
def m(k, v): L.append(f"\\newcommand{{\\{k}}}{{{v}}}")
pct = lambda x: f"{100 * x:.0f}"
m("pxPrecGpt", pct(s["labellers"]["gpt-5.6-sol"]["weighted_precision"]))
m("pxPrecGem", pct(s["labellers"]["gemini-3.1-pro"]["weighted_precision"]))
cs = s["consensus"]["per_stratum"]
m("pxPrecWrongfn", pct(cs["wrong-function"]["precision"]))
m("pxPrecPartial", pct(cs["partial-args"]["precision"]))
m("pxKappa", f"{s['kappa_progress']:.2f}")
m("pxNunique", str(sum(s["population"].values())))
m("pxNlabelled", str(s["n_labelled"]))
m("pxCollRQone", f"{100 * c['rq1']['fp_rate']:.2f}")
m("pxCollRQtwo", f"{100 * c['rq2']['fp_rate']:.2f}")
m("pxCollFrontier", f"{100 * c['frontier']['fp_rate']:.1f}")
open(os.path.join(H, "..", "out", "px_numbers.tex"), "w").write("\n".join(L) + "\n")
print("\n".join(L[1:]))
