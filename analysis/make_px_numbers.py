"""Macros for the plan §10 construct-validity checks, from runs/px/*.json (no hand values).
python3 make_px_numbers.py -> out/px_numbers.tex"""
import json, os, re
from fractions import Fraction
from efmt import F, exact, mean  # noqa: E402,F401  one half-up formatter
H = os.path.dirname(os.path.abspath(__file__)); PX = os.path.join(H, "..", "runs", "px")
s = json.load(open(os.path.join(PX, "px2_summary.json"))); c = json.load(open(os.path.join(PX, "px1a.json")))
L = ["% auto-generated by make_px_numbers.py (plan §10)"]
def m(k, v): L.append(f"\\newcommand{{\\{k}}}{{{v}}}")
pct = lambda x: f"{F(100 * x, '.0f')}"
def prec(v):   # exact per-class precision: progress over progress plus not progress
    return Fraction(v["progress"], v["progress"] + v["not_progress"])
def wprec(who):   # exact population-weighted precision, the estimand of px2_label.py score
    ps, pop = s["labellers"][who]["per_stratum"], s["population"]
    return sum(Fraction(pop[k], sum(pop.values())) * prec(ps[k]) for k in pop if ps[k]["progress"] + ps[k]["not_progress"])
for who in ("gpt-5.6-sol", "gemini-3.1-pro"):
    assert abs(float(wprec(who)) - s["labellers"][who]["weighted_precision"]) < 1e-12   # same estimand as the JSON
m("pxPrecGpt", pct(wprec("gpt-5.6-sol")))
m("pxPrecGem", pct(wprec("gemini-3.1-pro")))
# per-labeller per-class precision (the consensus per class drops disagreements, so it is not either labeller's figure)
for who, tag in (("gpt-5.6-sol", "Gpt"), ("gemini-3.1-pro", "Gem")):
    ps = s["labellers"][who]["per_stratum"]
    m(f"pxPrecWrongfn{tag}", pct(prec(ps["wrong-function"])))
    m(f"pxPrecPartial{tag}", pct(prec(ps["partial-args"])))
m("pxKappa", f"{F(s['kappa_progress'], '.3f')}")
m("pxKappaThree", f"{F(s['kappa_3label'], '.3f')}")
m("pxDisagreeN", str(exact(s["ambiguity_share"], s["n_labelled"]) * s["n_labelled"]))
m("pxNunique", str(sum(s["population"].values())))
m("pxNlabelled", str(s["n_labelled"]))
m("pxCollRQone", f"{F(Fraction(100 * c['rq1']['fires'], c['rq1']['pairs']), '.2f')}")
m("pxCollRQtwo", f"{F(Fraction(100 * c['rq2']['fires'], c['rq2']['pairs']), '.2f')}")
m("pxCollFrontier", f"{F(Fraction(100 * c['frontier']['fires'], c['frontier']['pairs']), '.1f')}")
# collision rate on the parse-gate models only (px1a_collision.py --models)
gp = os.path.join(PX, "px1a_gate.json")
if os.path.exists(gp):
    g = json.load(open(gp))
    m("pxCollGateRQone", f"{F(Fraction(100 * g['rq1']['fires'], g['rq1']['pairs']), '.1f')}")
    m("pxCollGateRQtwo", f"{F(Fraction(100 * g['rq2']['fires'], g['rq2']['pairs']), '.1f')}")
    m("pxCollGatePairs", f"{g['rq1']['pairs'] + g['rq2']['pairs']:,}")
    m("pxCollGate", f"{F(Fraction(100 * (g['rq1']['fires'] + g['rq2']['fires']), g['rq1']['pairs'] + g['rq2']['pairs']), '.1f')}")
# sampling rule and mix of the labelled set (plan §10.2)
m("pxPopPartial", str(s["population"]["partial-args"]))
m("pxPopWrongfn", str(s["population"]["wrong-function"]))
m("pxPopOther", str(s["population"]["other"]))
m("pxPopWrongfnPct", f"{F(Fraction(100 * s['population']['wrong-function'], sum(s['population'].values())), '.0f')}")
m("pxSamplePartial", str(s["consensus"]["per_stratum"]["partial-args"]["n_items"]))
# post-hoc: precision weighted by runs instead of distinct calls (px2_label.py runweight)
w = json.load(open(os.path.join(PX, "px2_runweight.json")))
m("pxRunPrecGpt", pct(w["gpt-5.6-sol"]["run_weighted_precision"]))
m("pxRunPrecGem", pct(w["gemini-3.1-pro"]["run_weighted_precision"]))
# post-hoc: RQ3 level-three share against its per-run collision floor (rq3_floor_test.py)
f = json.load(open(os.path.join(PX, "rq3_floor.json"))); p = f["pooled"]
own = float(re.search(r"rqthreeLthreePct\}\{([\d.]+)", open(os.path.join(H, "..", "out", "rq3_numbers.tex")).read()).group(1))
assert abs(100 * p["own_rate"] - own) < 0.05, "floor test own rate differs from RQ3 density"
m("pxFloorPct", f"{F(100 * p['floor_rate'], '.1f')}")
m("pxFloorDiff", f"{F(100 * p['mean_diff'], '.2f')}")
m("pxFloorLo", f"{F(100 * p['ci95'][0], '.2f')}")
m("pxFloorHi", f"{F(100 * p['ci95'][1], '.2f')}")
m("pxFloorP", f"{F(p['p_one_sided'], '.1g')}")
sig = [k for k, v in f["per_model"].items() if v["p_one_sided"] < 0.05 and v["mean_diff"] > 0]
below = [k for k, v in f["per_model"].items() if v["mean_diff"] < 0]
TAG = {"claude-sonnet-5": "Claude", "gpt-5.6-sol": "GptSol", "kimi-k3": "Kimi", "glm-5.3": "Glm",
       "gemini-3.1-pro": "Gemini", "deepseek-v4.1-flash": "Deepseek"}   # as make_rq3_numbers.py
for k, v in f["per_model"].items():
    m(f"pxFloorPm{TAG[k]}Pct", f"{F(100 * v['floor_rate'], '.1f')}")
    m(f"pxFloorPm{TAG[k]}P", f"{F(v['cluster_target']['p_one_sided'], '.2f')}")
ct, cm = f["pooled_cluster_pair"], f["pooled_cluster_model"]   # main test: the 15 shared target pairs as clusters
cmt = f["pooled_cluster_target"]
m("pxFloorMtP", f"{F(cmt['p_one_sided'], '.2f')}")
m("pxFloorClP", f"{F(ct['p_one_sided'], '.2f')}"); m("pxFloorClLo", f"{F(100 * ct['ci95'][0], '.2f')}"); m("pxFloorClHi", f"{F(100 * ct['ci95'][1], '.2f')}")
m("pxFloorClN", str(ct["clusters"])); dc = f["density_ci_target_cluster"]
m("pxOwnLo", f"{F(100 * dc['own'][0], '.1f')}"); m("pxOwnHi", f"{F(100 * dc['own'][1], '.1f')}")
m("pxFloorDLo", f"{F(100 * dc['floor'][0], '.1f')}"); m("pxFloorDHi", f"{F(100 * dc['floor'][1], '.1f')}"); m("pxFloorModP", f"{F(cm['p_one_sided'], '.2f')}")
# post-hoc: RQ1 with wrong-function level-three runs demoted to level two (rq1_demote.py)
d = json.load(open(os.path.join(PX, "rq1_demote.json")))
m("pxDemPass", str(len(d["C2"]["passed"])))
m("pxDemCentredRho", f"{F(d['pooled_model_centred']['rho'], '.3f')}")
m("pxDemQwenThirtyTwoBHolm", f"{F(d['qwen3-32b-local']['holm_p'], '.4f')}")
m("pxDemHoPooledRho", d["heldout_macros"]["rqonehoPooledRho"])
m("pxDemHoPooledP", d["heldout_macros"]["rqonehoPooledP"])
m("pxDemHoPass", d["heldout_macros"]["rqonehoPass"])
# E-PX1b benign control (px1b_benign.py) and the empty-trace share it is compared with (RQ1 Qwen3-8B census)
import glob, math
b = json.load(open(os.path.join(PX, "px1b.json")))
n, k, z = b["runs"], b["fires"], 1.96
ph = k / n; up = (ph + z * z / (2 * n) + z * math.sqrt(ph * (1 - ph) / n + z * z / (4 * n * n))) / (1 + z * z / n)
m("pxBenignN", str(n)); m("pxBenignFires", str(k)); m("pxBenignUpper", f"{F(100 * up, '.1f')}")
B = [json.loads(l) for l in open(os.path.join(PX, "px1b_runs.jsonl"))]; B = [r for r in B if r.get("err") is None]
m("pxBenignEmptyPct", f"{F(Fraction(100 * sum(not r['trace'] for r in B), len(B)), '.1f')}")
C = [json.loads(l) for f in glob.glob(os.path.join(H, "..", "runs", "rq1", "census_qwen3-8b-yf*.jsonl")) if "ABORTED" not in f for l in open(f)]
C = [r for r in C if r.get("err") is None and r.get("trace") is not None]
m("pxRQoneEmptyPct", f"{F(Fraction(100 * sum(not r['trace'] for r in C), len(C)), '.1f')}")
# post-hoc: held-out control on undefended units only (rq1_heldout_undef.py)
u = json.load(open(os.path.join(PX, "rq1_heldout_undef.json")))
# S1: the frozen text said p < 0.001; after the Qwen rerun it no longer holds, so p is emitted as a macro instead of asserted
m("pxUndefHoPooledP", f"{F(u['pooled']['p'], '.2g')}")
m("pxUndefHoPooledRho", f"{F(u['pooled']['rho'], '.3f')}"); m("pxUndefHoN", str(u["pooled"]["n"])); m("pxUndefHoPass", str(u["npass"]))
# post-hoc: RQ1 with the target as cluster (rq1_cluster.py)
q = json.load(open(os.path.join(PX, "rq1_cluster.json")))
for mk, tag in (("qwen3-8b-yf", "QwenEightB"), ("qwen3-32b-local", "QwenThirtyTwoB"), ("llama31-8b-local", "Llama"), ("granite31-8b-local", "Granite")):
    v = q["per_model"][mk]; m(f"pxClPm{tag}Lo", f"{F(v['ci95'][0], '.3f')}"); m(f"pxClPm{tag}Hi", f"{F(v['ci95'][1], '.3f')}")
m("pxClPmGraniteDraws", f"{q['per_model']['granite31-8b-local']['draws']:,}")   # resamples where rho is defined
import re as _re   # total bootstrap resamples B of rq1_cluster.py, read from its source so no rerun is needed
sp = json.load(open(os.path.join(PX, "rq1_samepop.json")))["pooled_centred"]   # Table S3 pooled row, same units as held-out
m("pxSamePopHoUnitsRho", F(sp["same_rep_on_heldout_units"]["rho"], ".3f")); m("pxSamePopHoUnitsN", str(sp["held_out"]["n"]))
m("pxClBootTotal", f"{int(_re.search(r'^B, SEED = (\d+)', open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'rq1_cluster.py')).read(), _re.M).group(1)):,}")
for k, tag in (("pooled_same", "Same"), ("pooled_heldout", "Ho")):
    m(f"pxCl{tag}Lo", f"{F(q[k]['ci95'][0], '.3f')}"); m(f"pxCl{tag}Hi", f"{F(q[k]['ci95'][1], '.3f')}"); m(f"pxCl{tag}P", f"{F(q[k]['p_one_sided'], '.3f')}")
# unweighted precision over the labelled sample (the headline figures reweight the strata to the population)
for who, tag in (("gpt-5.6-sol", "Gpt"), ("gemini-3.1-pro", "Gem")):
    ps = s["labellers"][who]["per_stratum"]
    kk = sum(v["progress"] for v in ps.values()); nn = sum(v["progress"] + v["not_progress"] for v in ps.values())
    m(f"pxPrecRaw{tag}", f"{F(Fraction(100 * kk, nn), '.0f')}")
# E-PX3 (plan 10.3): equal fresh budget, separate memo per arm (px3_fresh.py)
x = json.load(open(os.path.join(PX, "px3.json")))
for arm, tag in (("binary", "Bin"), ("prox-v21", "Prox"), ("tmap-ladder", "Tmap")):
    if arm not in x["arms"]:      # T-MAP not rerun (S1)
        continue
    m(f"pxThree{tag}Dist", f"{F(exact(x['arms'][arm]['distinct_mean'], x['units']), '.2f')}")
m("pxThreeUnits", str(x["units"]))
for k, tag in (("prox-v21_vs_binary", "ProxBin"), ("tmap-ladder_vs_binary", "TmapBin"), ("tmap-ladder_vs_prox-v21", "TmapProx")):
    if k not in x["primary"]:
        continue
    m(f"pxThree{tag}A", f"{F(exact(x['primary'][k]['A12'], 2 * x['units']), '.3f')}"); m(f"pxThree{tag}Holm", f"{F(x['primary'][k]['holm'], '.2g')}")
for arm, tag in (("binary", "Bin"), ("prox-v21", "Prox")):   #: KM medians of executions to first success
    m(f"pxThree{tag}KM", str(x["arms"][arm]["km_median_first"]))
    m(f"pxThree{tag}Hits", str(x["arms"][arm]["memo_hits"]))   # within-variant memo hits (codex r11)
m("pxThreeLogrankMinP", f"{F(min(v['p'] for v in x['secondary'].values()), '.2f')}")
# plan 11 post-hoc definition ablation, five arms, separate memo each (ablate_r3.py; S1 rerun on the same cluster as RQ4)
y = json.load(open(os.path.join(PX, "ablate_r3.json")))
for arm, tag in (("binary", "Bin"), ("prox-v21", "Prox"), ("prox-l3", "Lthree")):
    m(f"pxAb{tag}Dist", f"{F(exact(y['arms'][arm]['distinct_mean'], y['units']), '.2f')}")
m("pxAbRepA", f"{F(exact(y['binary_vs_prox_replication']['A12'], 2 * y['units']), '.3f')}"); m("pxAbRepP", f"{F(y['binary_vs_prox_replication']['p_two_sided'], '.2g')}")
m("pxAbLthreeBinA", f"{F(exact(y['vs_binary']['prox-l3']['A12'], 2 * y['units']), '.3f')}"); m("pxAbLthreeBinHolm", f"{F(y['vs_binary']['prox-l3']['holm'], '.2g')}")
m("pxAbLthreeProxA", f"{F(exact(y['vs_prox']['prox-l3']['A12'], 2 * y['units']), '.3f')}"); m("pxAbLthreeProxHolm", f"{F(y['vs_prox']['prox-l3']['holm'], '.2g')}")
# caption tail computed from the data
_d = {a: exact(y['arms'][a]['distinct_mean'], y['units']) for a in ("prox-l3", "binary", "prox-v21")}
_inside = min(_d["binary"], _d["prox-v21"]) <= _d["prox-l3"] <= max(_d["binary"], _d["prox-v21"])
ABL_TAIL = ("A2 averaged %s distinct payloads against %s for binary success and %s for proximity, so its mean fell %s the predicted range. "
            % (F(_d["prox-l3"], '.2f'), F(_d["binary"], '.2f'), F(_d["prox-v21"], '.2f'), "inside" if _inside else "outside"))
_err = sum(a.get("errors", 0) for a in y["arms"].values())
_sch = sum(v["rows"] for v in y.get("excluded_schema_text", {}).values())
if _err:
    ABL_TAIL += "The counts treat %d executions that ended in an engine error as executions without a violation. " % _err
if _sch:
    ABL_TAIL += "The table leaves out %d executions whose output holds tool-schema text. " % _sch
ABL_TAIL = ABL_TAIL.rstrip() + "}"
NAME = {"binary": "binary success", "prox-v21": "proximity", "prox-nowf": "A1 wrong function demoted",
        "prox-l3": "A2 levels three and four only", "prox-perm": "A3 sampled past level"}
T = ["\\begin{table}[t]\\centering\\small",
     "\\caption{Post-hoc reward-definition ablation on Qwen3-8B, run with a separate memo per \\varword{} over %d paired campaigns of forty executions. "
     "Distinct is the mean number of distinct violating payloads per campaign $\\uparrow$. Each $\\hat A_{12}$ compares the row \\varword{} with the column \\varword{}, with Holm-adjusted $p$ over the three ablation \\varwords{}, except the binary-success row, whose $p$ is two-sided and unadjusted. "
     "Median first success is the Kaplan-Meier median of executions to the first violation $\\downarrow$. "
     "A1 scores a level-three run as level two when its first flagged call uses a function outside the attacker task. "
     "A2 gives reward 1 at level three or four and 0 otherwise, which adds level-three runs to the runs that binary success rewards. "
     "A3 rewards each run with a level drawn at random from the levels its campaign has seen so far, the current run included. "
     "The predictions registered before the runs were A1 at or above proximity, A2 between proximity and binary success and A3 close to proximity. "
     % y["units"] + ABL_TAIL,
     "\\label{tab:ablate}", "\\begin{tabular}{lcccc}", "\\toprule",
     "\\Varword{} & Distinct $\\uparrow$ & median first success $\\downarrow$ & $\\hat A_{12}$ vs proximity & $\\hat A_{12}$ vs binary \\\\", "\\midrule"]
def cell(fam, a):
    v = y[fam].get(a); return "--" if v is None else f"{F(exact(v['A12'], 2 * y['units']), '.3f')}, $p=$\\,{F(v['holm'], '.2g')}"
for a in ("binary", "prox-v21", "prox-nowf", "prox-l3", "prox-perm"):
    r = y["arms"][a]; vp = cell("vs_prox", a); vb = cell("vs_binary", a)
