"""RQ1 held-out circularity control (post-review, rule in NOTES). Even-index reps -> mean level,
odd-index reps -> trigger rate, per (suite,ut,it,defense) unit. Spearman per model + pooled.
python3 rq1_heldout.py -> out/rq1ho_numbers.tex (+ prints a table)
"""
import collections
import glob
import json
import os
import statistics as st
import sys

from scipy.stats import spearmanr

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "engine"))
import engagefuzz as ef  # noqa: E402

MODELS = [("qwen3-8b-yf", "QwenEightB"), ("qwen3-32b-local", "QwenThirtyTwoB"),
          ("llama31-8b-local", "Llama"), ("granite31-8b-local", "Granite")]


def main():
    L = ["% auto-generated by rq1_heldout.py (post-review held-out control)"]
    def m(k, v): L.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    PX, PY, npass = [], [], 0
    for mk, tag in MODELS:
        files = [f for f in glob.glob(os.path.join(HERE, "..", "runs", "rq1", f"census_{mk}*.jsonl")) if "ABORTED" not in f]
        R = [json.loads(l) for f in files for l in open(f)]
        R = [r for r in R if r.get("err") is None and r.get("trace") is not None]
        for r in R:
            r["_lv"] = ef.prox_v2.feats(r)["level21"]
        cells = collections.defaultdict(list)
        for r in R:
            cells[(r["suite"], r["ut"], r["it"], r["defense"])].append(r)
        X, Y = [], []
        for v in cells.values():
            A = [x for x in v if x["rep"] % 2 == 0]   # even-rep -> level
            B = [x for x in v if x["rep"] % 2 == 1]   # odd-rep  -> trigger rate
            fa = [x for x in A if not x["security"]]
            if A and B and fa:
                X.append(st.mean(x["_lv"] for x in fa)); Y.append(st.mean(bool(x["security"]) for x in B))
        rr = spearmanr(X, Y) if len(X) > 2 and len(set(X)) > 1 and len(set(Y)) > 1 else (float("nan"), float("nan"))
        sig = rr[1] < 0.05 and rr[0] > 0
        npass += sig
        m(f"rqoneho{tag}Rho", f"{rr[0]:.3f}"); m(f"rqoneho{tag}P", f"{rr[1]:.3g}")
        mx, my = (st.mean(X), st.mean(Y)) if X else (0, 0)
        PX += [a - mx for a in X]; PY += [b - my for b in Y]
        print(f"{mk:20} held-out rho={rr[0]:.3f} p={rr[1]:.3g} n={len(X)} sig={sig}")
    # robustness: 300 random half-splits per unit, pooled model-centred Spearman each
    import random as _rnd
    allcells = []
    for mk, _ in MODELS:
        files = [f for f in glob.glob(os.path.join(HERE, "..", "runs", "rq1", f"census_{mk}*.jsonl")) if "ABORTED" not in f]
        R = [json.loads(l) for f in files for l in open(f)]
        R = [r for r in R if r.get("err") is None and r.get("trace") is not None]
        for r in R:
            r["_lv"] = ef.prox_v2.feats(r)["level21"]
        cc = collections.defaultdict(list)
        for r in R:
            cc[(mk, r["suite"], r["ut"], r["it"], r["defense"])].append(r)
        allcells.append((mk, cc))
    dist = []
    rng = _rnd.Random(0)
    for _ in range(300):
        PXr, PYr = [], []
        for mk, cc in allcells:
            Xr, Yr = [], []
            for v in cc.values():
                idx = list(range(len(v))); rng.shuffle(idx)
                A = [v[i] for i in idx[:len(v)//2]]; B = [v[i] for i in idx[len(v)//2:]]
                fa = [x for x in A if not x["security"]]
                if A and B and fa:
                    Xr.append(st.mean(x["_lv"] for x in fa)); Yr.append(st.mean(bool(x["security"]) for x in B))
            if Xr:
                mx, my = st.mean(Xr), st.mean(Yr); PXr += [a-mx for a in Xr]; PYr += [b-my for b in Yr]
        rr2 = spearmanr(PXr, PYr)
        if rr2[0] == rr2[0]:
            dist.append(rr2[0])
    dist.sort()
    m("rqonehoRandMed", f"{dist[len(dist)//2]:.3f}")
    m("rqonehoRandLo", f"{dist[int(0.025*len(dist))]:.3f}"); m("rqonehoRandHi", f"{dist[int(0.975*len(dist))-1]:.3f}")
    print(f"random-split pooled rho: median={dist[len(dist)//2]:.3f} 95%=[{dist[int(0.025*len(dist))]:.3f},{dist[int(0.975*len(dist))-1]:.3f}]")
    pr = spearmanr(PX, PY)
    m("rqonehoPooledRho", f"{pr[0]:.3f}"); m("rqonehoPooledP", f"{pr[1]:.2g}"); m("rqonehoPass", str(npass))
    open(os.path.join(HERE, "..", "out", "rq1ho_numbers.tex"), "w").write("\n".join(L) + "\n")
    print(f"pooled held-out rho={pr[0]:.3f} p={pr[1]:.3g} | per-model sig {npass}/4")


if __name__ == "__main__":
    main()
