"""Gateway sensitivity, post-hoc. Offline, zero model calls.
python3 gateway_sens.py -> out/gateway_numbers.tex
RQ3 without gpt-5.6-sol, from runs/px/rq3_floor_nosol.json (`rq3_floor_test.py --exclude gpt-5.6-sol`):
level-three share of failed frontier runs, collision floor and the target-pair cluster test, formatted as
make_px_numbers.py formats the six-model values.
"""
import json
import os
from fractions import Fraction

from efmt import F  # noqa: E402  one half-up formatter

H = os.path.dirname(os.path.abspath(__file__))
f = json.load(open(os.path.join(H, "..", "runs", "px", "rq3_floor_nosol.json")))
p, ct = f["pooled"], f["pooled_cluster_pair"]
fr = [json.loads(l) for l in open(os.path.join(H, "..", "testbed", "data", "frontier.jsonl"))]
fail = [r for r in fr if r.get("err") is None and r.get("trace") is not None and not r["security"] and r["model"] != "gpt-5.6-sol"]
import prox_v2 as P  # noqa: E402
l3 = sum(P.feats(r)["level21"] == 3 for r in fail)
assert abs(l3 / len(fail) - p["own_rate"]) < 1e-12, "level-three count differs from rq3_floor_nosol.json"
L = ["% auto-generated by gateway_sens.py; do not hand-edit"]
m = lambda k, v: L.append(f"\\newcommand{{\\{k}}}{{{v}}}")
m("gwNoSolModels", "5")
m("gwNoSolFail", str(len(fail)))
m("gwNoSolLthree", str(l3))
m("gwNoSolLthreePct", F(Fraction(100 * l3, len(fail)), ".1f"))
m("gwNoSolFloorPct", F(100 * p["floor_rate"], ".1f"))
m("gwNoSolDiff", F(100 * p["mean_diff"], ".2f"))
m("gwNoSolClLo", F(100 * ct["ci95"][0], ".2f"))
m("gwNoSolClHi", F(100 * ct["ci95"][1], ".2f"))
m("gwNoSolClP", F(ct["p_one_sided"], ".2f"))
open(os.path.join(H, "..", "out", "gateway_numbers.tex"), "w").write("\n".join(L) + "\n")
print("\n".join(L))

# gateway billing quantiles (runs/px/gateway_quantiles_release.json): bounds on the share of calls with an added prefix
q = json.load(open(os.path.join(H, "..", "runs", "px", "gateway_quantiles_release.json")))
r3 = q["rq3_window"]
assert r3["gpt-5.6-sol"][0] > max(v[0] for k, v in r3.items() if k != "gpt-5.6-sol")   # p10 above every other model
L2 = []
m2 = lambda k, v: L2.append(f"\\newcommand{{\\{k}}}{{{v}}}")
m2("gwSolRqthreePten", str(r3["gpt-5.6-sol"][0]))
m2("gwOtherRqthreePtenMax", str(max(v[0] for k, v in r3.items() if k != "gpt-5.6-sol")))
m2("gwSolLabelMed", str(q["px2_window"]["gpt-5.6-sol"][1]))
m2("gwGemLabelMed", str(q["px2_window"]["gemini-3.1-pro"][1]))
m2("gwJudgePninety", str(q["px3_window"]["gpt-5.5"][2]))
m2("gwJudgeRqtwoLogged", str(q["rq2_window"]["judge_calls_logged_token"]))
import glob as _g
_fresh = sum(1 for f in _g.glob(os.path.join(H, "..", "runs", "rq2", "*tmap-ladder_[0-9].jsonl")) for l in open(f)
             for r in [json.loads(l)] if not r.get("memo_hit") and r.get("err") is None)
assert _fresh == q["rq2_window"]["expected_judge_calls"]
m2("gwJudgeRqtwoExpected", str(_fresh))
open(os.path.join(H, "..", "out", "gateway_numbers.tex"), "a").write("\n".join(L2) + "\n")
print("\n".join(L2))

# SI table of injected-prefix shares uniform format; EF has no per-call usage, so every row is a
# window-quantile bound or not attributable
off = list(q["probe_offset_tokens"].values())   # five other frontier models
N = q["n"]
# share bound from window quantiles: a quantile counts as prefixed when it exceeds the comparison quantile by more
# than half the probed gpt-5.6-sol prefix. All of p10/p50/p90 prefixed -> >=90%; p50,p90 only -> 50% to 90%;
# none of p10/p50/p90 -> <=10%. Comparison: RQ3 = max over the other models, labeller = gemini-3.1-pro,
# T-MAP judge (no second judge in the window) = its own p50.
HALF = q["probe_prefix_tokens"]["gpt-5.6-sol"] / 2
def bound(qs, ref):
    pre = [a - b > HALF for a, b in zip(qs[:3], ref[:3])]
    return {(True, True, True): r"$\geq$90\%", (False, True, True): r"50\% to 90\%",
            (False, False, False): r"$\leq$10\%"}[tuple(pre)]
ref3 = [max(v[i] for k, v in r3.items() if k != "gpt-5.6-sol") for i in range(3)]
j = q["px3_window"]["gpt-5.5"]
n_rq4 = sum(1 for _ in open(os.path.join(H, "..", "runs", "rq4", "injecagent_frontier_gpt-5.6-sol.jsonl")))
rows = [("gpt-5.6-sol", "RQ3 frontier agent", str(N["rq3_gpt-5.6-sol"]), bound(r3["gpt-5.6-sol"], ref3), "inferred from window quantiles"),
        ("gpt-5.6-sol", "RQ4 frontier agent", str(n_rq4), "not attributable", "window shared with another study"),
        ("gpt-5.6-sol", "labeller", str(N["px2_gpt-5.6-sol"]), bound(q["px2_window"]["gpt-5.6-sol"], q["px2_window"]["gemini-3.1-pro"]), "inferred from window quantiles"),
        ("gpt-5.5", "T-MAP judge, one memo per reward \\varword{}", str(N["px3_gpt-5.5"]), bound(j, [j[1]] * 3), "inferred from window quantiles"),
        ("gpt-5.5", "T-MAP judge, shared memo", str(_fresh), "cannot be checked", "calls not under the logged token"),
        ("five other frontier models", "RQ3 and RQ4 agents", "--", "not resolvable", f"probe prefix {F(min(off), '.0f')} to {F(max(off), '.0f')} tokens")]
T = ["% auto-generated by gateway_sens.py; do not hand-edit",
     r"\begin{table}[t]\centering",
     r"\caption{Calls through the API gateway that carry an added prefix. We recorded no per-call token counts, so each share is a bound inferred from the billed prompt-token quantiles of the gateway per model and time window, not a per-call measurement. The last row gives the fixed prefix length that a probe on 2026-10-17 measured for the other five frontier models, which the window quantiles cannot resolve.}",
     r"\label{tab:gateway}", r"\begin{tabular}{llrll}", r"\toprule",
     r"Model & Role & Calls & Share with prefix & Basis \\", r"\midrule"]
T += [" & ".join(r) + r" \\" for r in rows]
T += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
open(os.path.join(H, "..", "out", "gateway_table.tex"), "w").write("\n".join(T) + "\n")
