"""RQ3 frontier-density macros from the frozen frontier logs (no hand numbers).
python3 make_rq3_numbers.py -> out/rq3_numbers.tex

Reads testbed/data/frontier.jsonl, grades each run with the v2.1 proximity ladder
(engangefuzz prox_v2.feats level21), and reports: number of frontier models, pooled
attack-success rate, number of binary-failure runs, the level-three and level-two-or-higher
shares among those failures, and the models with a zero attack-success rate.
"""
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "engine"))
import engagefuzz as ef  # noqa: E402
from fractions import Fraction
from efmt import F, exact, mean  # noqa: E402,F401  one half-up formatter

FRONTIER = os.path.join(HERE, "..", "testbed", "data", "frontier.jsonl")
OUT = os.path.join(HERE, "..", "out", "rq3_numbers.tex")
DISP = {"qwen3-8b-yf": "Qwen3-8B", "qwen3-32b-local": "Qwen3-32B",
        "llama31-8b-local": "Llama-3.1-8B", "granite31-8b-local": "Granite-3.1-8B"}


def disp(m):
    return DISP.get(m, m)


def main():
    R = [json.loads(l) for l in open(FRONTIER)]
    R = [r for r in R if r.get("err") is None and r.get("trace") is not None]
    for r in R:
        r["_l21"] = ef.prox_v2.feats(r)["level21"]
    models = sorted({r["model"] for r in R})
    asr = {m: Fraction(sum(bool(r["security"]) for r in R if r["model"] == m), max(1, sum(r["model"] == m for r in R)))
           for m in models}
    pooled_asr = Fraction(sum(bool(r["security"]) for r in R), max(1, len(R)))
    nv = [r for r in R if not r["security"]]
    l3 = sum(r["_l21"] == 3 for r in nv)
    l2plus = sum(r["_l21"] >= 2 for r in nv)
    zero = [disp(m) for m in models if asr[m] == 0]
    zero_str = " and ".join(zero) if len(zero) <= 2 else ", ".join(zero[:-1]) + " and " + zero[-1]
    L = ["% auto-generated by make_rq3_numbers.py (frontier density, v2.1 ladder)"]
    def m(k, v): L.append(f"\\newcommand{{\\{k}}}{{{v}}}")
    m("rqthreeModels", str(len(models)))
    m("rqthreeASRpct", f"{F(100 * pooled_asr, '.1f')}")
    m("rqthreeNonviol", str(len(nv)))
    m("rqthreeLthree", str(l3))
    m("rqthreeLthreePct", f"{F(Fraction(100 * l3, max(1, len(nv))), '.1f')}")
    m("rqthreeLtwoPlusPct", f"{F(Fraction(100 * l2plus, max(1, len(nv))), '.1f')}")
    _pairs = {}
    for r in nv:
        if r["_l21"] == 3:
            _pairs.setdefault(r["model"], set()).add((r["suite"], r["ut"], r["it"]))
    m("rqthreeLthreePairsMaxPerModel", str(max(len(v) for v in _pairs.values())))
    m("rqthreeLthreePairsAll", str(len(set().union(*_pairs.values()))))
    m("rqthreePairs", str(len({(r["suite"], r["ut"], r["it"]) for r in R})))
    m("rqthreeLzeroPct", f"{F(Fraction(100 * sum(r['_l21'] == 0 for r in nv), max(1, len(nv))), '.1f')}")
    m("rqthreeLonePct", f"{F(Fraction(100 * sum(r['_l21'] == 1 for r in nv), max(1, len(nv))), '.1f')}")
    # per-model density macros (frontier table)
    TAG = {"claude-sonnet-5": "Claude", "gpt-5.6-sol": "GptSol", "kimi-k3": "Kimi",
           "deepseek-v4.1-flash": "Deepseek", "glm-5.3": "Glm", "gemini-3.1-pro": "Gemini"}
    for mm in models:
        rm = [r for r in R if r["model"] == mm]
        nvm = [r for r in rm if not r["security"]]
        t = TAG.get(mm, mm.split("-")[0].title())
        m(f"rqthreePm{t}N", str(len(rm)))
        m(f"rqthreePm{t}ASR", f"{F(100 * asr[mm], '.1f')}")
        m(f"rqthreePm{t}Nonviol", str(len(nvm)))
        m(f"rqthreePm{t}Lthree", str(sum(r['_l21'] == 3 for r in nvm)))
        m(f"rqthreePm{t}LthreePct", f"{F(Fraction(100 * sum(r['_l21'] == 3 for r in nvm), max(1, len(nvm))), '.1f')}")
    open(OUT, "w").write("\n".join(L) + "\n")
    print("\n".join(L[1:]))


if __name__ == "__main__":
    main()
